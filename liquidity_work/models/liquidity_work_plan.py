# -*- coding: utf-8 -*-
import logging

from odoo import api, fields, models

_logger = logging.getLogger(__name__)


class LiquidityWorkPlan(models.Model):
    """A sold plan: a copy of a template, tied to one bookkeeping.

    Created once when a sale order is confirmed. It carries no work orders at
    creation — those appear as their periods approach, generated by cron.
    """

    _name = "liquidity.work.plan"
    _description = "Work plan"
    _inherit = ["mail.thread"]
    _order = "date_start desc, id desc"

    name = fields.Char(string="Plan", required=True, tracking=True)
    template_id = fields.Many2one(
        "liquidity.work.template",
        string="From template",
        readonly=True,
        ondelete="set null",
        help="Traceability back to the template this plan was copied from. "
             "Editing the template afterwards does not change this plan.",
    )
    company_id = fields.Many2one(
        "liquidity.tenant.company",
        string="Bookkeeping",
        required=True,
        ondelete="cascade",
        tracking=True,
    )
    sale_line_id = fields.Many2one(
        "sale.order.line",
        string="Sale line",
        readonly=True,
        ondelete="set null",
        index=True,
        help="The line this plan came from. Used for idempotency: confirming "
             "the same order twice must not create a second plan.",
    )
    sale_order_id = fields.Many2one(
        "sale.order",
        string="Sale order",
        related="sale_line_id.order_id",
        store=True,
        readonly=True,
    )
    partner_id = fields.Many2one(
        "res.partner",
        string="Customer",
        related="sale_line_id.order_id.partner_id",
        store=True,
        readonly=True,
    )
    date_start = fields.Date(
        string="Start",
        default=fields.Date.context_today,
        required=True,
    )
    date_end = fields.Date(
        string="End",
        help="Empty means the plan runs until it is archived.",
    )
    state = fields.Selection(
        selection=[("draft", "Draft"), ("running", "Running"), ("closed", "Closed")],
        string="Status",
        default="running",
        required=True,
    )
    line_ids = fields.One2many(
        "liquidity.work.plan.line",
        "plan_id",
        string="Lines",
    )
    order_ids = fields.One2many(
        "liquidity.work.order",
        "plan_id",
        string="Work orders",
    )
    order_count = fields.Integer(
        string="Work orders", compute="_compute_order_count"
    )
    open_order_count = fields.Integer(
        string="Open work orders", compute="_compute_order_count"
    )

    @api.depends("order_ids", "order_ids.state")
    def _compute_order_count(self):
        for plan in self:
            plan.order_count = len(plan.order_ids)
            plan.open_order_count = len(
                plan.order_ids.filtered(
                    lambda o: o.state in ("planned", "in_progress")
                )
            )

    @api.model
    def _liquidity_create_plan(self, template, company, sale_line=None, name=None):
        """Copy a template into a plan for one bookkeeping.

        The copy is the point: the template stays a template, and the plan is
        the customer's own copy that can be worked on without affecting anyone
        else's.
        """
        values = {
            "company_id": company.id,
            "template_id": template.id,
            "name": name or "%s — %s" % (company.name, template.name),
        }
        if sale_line:
            values["sale_line_id"] = sale_line.id
        plan = self.create(values)

        # ``template.copy()`` copies a record into its OWN model — it cannot
        # produce a plan. The copy is therefore explicit: each template line
        # becomes a plan line, which is what makes the plan independent of the
        # template from then on.
        self.env["liquidity.work.plan.line"].create([
            {
                "plan_id": plan.id,
                "template_line_id": line.id,
                "sequence": line.sequence,
                "name": line.name,
                "description": line.description,
                "interval_number": line.interval_number,
                "interval_type": line.interval_type,
                "offset_days": line.offset_days,
                "responsible_role": line.responsible_role,
                "estimated_minutes": line.estimated_minutes,
            }
            for line in template.line_ids
        ])
        return plan

    def action_close(self):
        self.write({"state": "closed"})
        return True

    def action_reopen(self):
        self.write({"state": "running"})
        return True


class LiquidityWorkPlanLine(models.Model):
    """One recurring action inside a plan, copied from a template line."""

    _name = "liquidity.work.plan.line"
    _description = "Work plan line"
    _order = "plan_id, sequence, id"

    plan_id = fields.Many2one(
        "liquidity.work.plan",
        string="Plan",
        required=True,
        ondelete="cascade",
        index=True,
    )
    template_line_id = fields.Many2one(
        "liquidity.work.template.line",
        string="From template line",
        readonly=True,
        ondelete="set null",
        help="Kept so a generated work order can be traced back to the action "
             "it came from, and so the unique constraint has a stable key.",
    )
    sequence = fields.Integer(default=10)
    name = fields.Char(string="Action", required=True)
    description = fields.Html(string="Description")
    description_excerpt = fields.Char(
        string="Description (text)",
        compute="_compute_description_excerpt",
        store=True,
    )
    interval_number = fields.Integer(string="Every", default=1, required=True)
    interval_type = fields.Selection(
        selection=[
            ("day", "Days"),
            ("week", "Weeks"),
            ("month", "Months"),
            ("year", "Years"),
        ],
        string="Unit",
        default="month",
        required=True,
    )
    offset_days = fields.Integer(string="Offset (days)", default=0)
    responsible_role = fields.Char(string="Responsible role")
    estimated_minutes = fields.Float(string="Estimated minutes")

    @api.depends("description")
    def _compute_description_excerpt(self):
        for line in self:
            line.description_excerpt = self.env[
                "liquidity.work.template.line"
            ]._excerpt(line.description)
